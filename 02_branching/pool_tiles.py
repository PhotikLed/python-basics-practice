"""Тема: Ветвления.

Задача: расчет плитки для облицовки бассейна.
Размер плитки 1х1 метр, считаем 4 стенки и дно.
"""


def count_tiles(dep, leng, wid=None):
    """Считает общее количество плиток для 4-х стенок и дна бассейна.

    :param dep: глубина бассейна
    :param leng: длина бассейна
    :param wid: ширина бассейна (если None, считается равной длине - квадратный бассейн)
    :return: суммарное количество плиток
    """
    # Если ширина не задана, бассейн квадратный
    if wid is None:
        wid = leng

    # Дно бассейна
    bottom = leng * wid

    # Стенки: две стенки площади dep * leng, две стенки площади dep * wid
    walls = 2 * (dep * leng) + 2 * (dep * wid)

    total = bottom + walls
    return total


if __name__ == '__main__':
    # Проверка примеров из задания:
    # 2x2, глубина 2 -> дно 4 + стенки 16 = 20
    print('Потребуется плиток:', count_tiles(2, 2))
    # 2x3, глубина 1 -> дно 6 + стенки 10 = 16
    print('Потребуется плиток:', count_tiles(1, 2, 3))
    # 5x3, глубина 2 -> дно 15 + стенки 32 = 47
    print('Потребуется плиток:', count_tiles(2, 5, 3))
