"""Тема: Коллекции.

Задача: определение места участника олимпиады по программированию.
Сравниваем результат студента с тройкой лучших результатов.
"""

from typing import List


def check_winners(scores: List[int], student_score: int) -> None:
    """Проверяет, входит ли балл студента в тройку максимальных результатов олимпиады.

    :param scores: список всех результатов участников
    :param student_score: количество баллов студента
    """
    # Сортируем баллы по убыванию и берем первые три
    # (по условию все студенты набрали разное количество баллов)
    top_three = sorted(scores, reverse=True)[:3]

    if student_score in top_three:
        print('Вы в тройке победителей!')
    else:
        print('Вы не попали в тройку победителей.')


